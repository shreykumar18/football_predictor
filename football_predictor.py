# Import necessary libraries
import pandas as pd
import numpy as np
import seaborn as sns
import matplotlib.pyplot as plt
from sklearn.preprocessing import KBinsDiscretizer
from sklearn.model_selection import train_test_split
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix

from pgmpy.models import BayesianNetwork
from pgmpy.estimators import MaximumLikelihoodEstimator
from pgmpy.inference import VariableElimination

import warnings
warnings.filterwarnings('ignore')

# Load datasets
games_df = pd.read_csv("games.csv")
teamstats_df = pd.read_csv("teamstats.csv")
shots_df = pd.read_csv("shots.csv")

print("✅ Datasets Loaded Successfully")

# Fill missing assisterID with 0 (assuming NA means no assist)
shots_df["assisterID"] = shots_df["assisterID"].replace("NA", np.nan).fillna(0)

# Fill missing numerical values with median
for col in teamstats_df.select_dtypes(include=[np.number]).columns:
    teamstats_df[col].fillna(teamstats_df[col].median(), inplace=True)

# Fill missing categorical values with "Unknown"
teamstats_df["location"].fillna("Unknown", inplace=True)

print("✅ Missing Values Handled")

# Encode match results: W = 1, D = 0, L = -1
label_map = {"W": 1, "D": 0, "L": -1}
teamstats_df["result"] = teamstats_df["result"].map(label_map)

# Convert date to datetime format
teamstats_df["date"] = pd.to_datetime(teamstats_df["date"])

# Rolling averages for last 5 matches (form-based features)
teamstats_df.sort_values(by=["teamID", "date"], inplace=True)
for stat in ["xGoals", "shots", "shotsOnTarget"]:
    teamstats_df[f"{stat}_rolling5"] = (
        teamstats_df.groupby("teamID")[stat].rolling(5, min_periods=1).mean().reset_index(level=0, drop=True)
    )

# Create Home/Away Feature
teamstats_df["is_home"] = (teamstats_df["location"] == "h").astype(int)

print("✅ Feature Engineering Completed")

# Select features to be used in the model
features = ["xGoals_rolling5", "shots_rolling5", "shotsOnTarget_rolling5", "is_home"]
X = teamstats_df[features]
y = teamstats_df["result"]

# Discretize continuous features into 3 bins (low, medium, high)
discretizer = KBinsDiscretizer(n_bins=2, encode="ordinal", strategy="uniform")
X_discrete = pd.DataFrame(discretizer.fit_transform(X), columns=features)
X_discrete["result"] = y.values

X_discrete = X_discrete.fillna(0)

print("✅ Data Discretized for Bayesian Network")

# Define Bayesian Network Structure
edges = [
    ("xGoals_rolling5", "result"),
    ("shots_rolling5", "result"),
    ("shotsOnTarget_rolling5", "result"),
    ("is_home", "result")
]

model = BayesianNetwork(edges)

print("✅ Bayesian Network Structure Defined")

# Fit the Bayesian Network
model.fit(X_discrete, estimator=MaximumLikelihoodEstimator)

# Initialize inference engine
inference = VariableElimination(model)

print("✅ Bayesian Network Trained Successfully")

# Split dataset into train & test
X_train, X_test, y_train, y_test = train_test_split(
    X_discrete.drop(columns=["result"]),  # Features
    X_discrete["result"],  # Target variable
    test_size=0.2, random_state=42
)

print("✅ Dataset Split into Train & Test")

import networkx as nx

# Convert Bayesian Network to a Graph
G = nx.DiGraph()
G.add_edges_from(model.edges())

# Check if there's a cycle in the graph
if nx.is_directed_acyclic_graph(G):
    print("✅ The Bayesian Network has NO cycles.")
else:
    print("❌ ERROR: The Bayesian Network contains a cycle! Fix the structure.")

# Function for batch inference with debugging and efficiency improvements
def batch_predict(inference, X_test):
    predictions = []
    total_rows = len(X_test)

    for i, row in X_test.iterrows():
        try:
            evidence = {col: int(row[col]) for col in X_test.columns}
        except ValueError as ve:
            print(f"⚠️ ValueError at row {i+1}: {ve}. Skipping row.")
            predictions.append(0)  # Assign default class and continue
            continue

        try:
            result = inference.map_query(variables=["result"], evidence=evidence, show_progress=False)
            predictions.append(result["result"])
        except Exception as e:
            print(f"❌ ERROR at row {i+1}: {e}")
            predictions.append(0)  # Default class if inference fails

        # Debugging: Print progress every 100 rows
        if (i + 1) % 100 == 0:
            print(f"✅ Processed {i+1}/{total_rows} rows")

    return predictions

# Run inference on test data
print("🚀 Running Bayesian Inference on Test Data...")
predictions = batch_predict(inference, X_test)

# Evaluate Model Performance
print("\n📊 Model Performance:")
print(classification_report(y_test, predictions))
print("Confusion Matrix:\n", confusion_matrix(y_test, predictions))
print("Accuracy:", accuracy_score(y_test, predictions))

print("✅ Model Evaluation Completed")

