from hmmlearn import hmm
import numpy as np
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import accuracy_score, classification_report
from scipy.stats import mode

# Step 1: Merge teamstats with games on gameID
merged_df = teamstats_df.merge(games_df, on='gameID', how='inner')
print("After merge on gameID: merged_df shape =", merged_df.shape)

# Step 2: Fix merged date column after merge
if 'date_x' in merged_df.columns:
    merged_df['date'] = merged_df['date_x']
elif 'date_y' in merged_df.columns:
    merged_df['date'] = merged_df['date_y']

# Step 3: Filter using correct home/away logic
merged_df = merged_df[
    ((merged_df['location'] == 'h') & (merged_df['teamID'] == merged_df['homeTeamID'])) |
    ((merged_df['location'] == 'a') & (merged_df['teamID'] == merged_df['awayTeamID']))
]
print("After correct home/away filtering: merged_df shape =", merged_df.shape)

# Step 4: Sort by team + date (to build sequences)
merged_df['date'] = pd.to_datetime(merged_df['date'])
merged_df = merged_df.sort_values(by=['teamID', 'date'])

# Step 5: Select features and target
features = ['xGoals', 'shotsOnTarget', 'deep', 'ppda']
target = 'result'

# Drop missing rows
merged_df = merged_df.dropna(subset=features + [target])

# Step 6: Standardize features
scaler = StandardScaler()
merged_df[features] = scaler.fit_transform(merged_df[features])

# Step 7: Group by team to build sequences
team_sequences = []
team_targets = []

for team_id, group in merged_df.groupby('teamID'):
    X_seq = group[features].values
    y_seq = group[target].values
    if len(X_seq) >= 5:  # Only take teams with enough matches
        team_sequences.append(X_seq)
        team_targets.append(y_seq)

# Step 8: Concatenate all sequences for HMM fitting
X_concat = np.concatenate(team_sequences)
lengths = [len(seq) for seq in team_sequences]

# Step 9: Train Gaussian HMM
model = hmm.GaussianHMM(n_components=3, covariance_type="diag", n_iter=100)
model.fit(X_concat, lengths)

# Step 10: Predict hidden states for each team sequence
hidden_states = []
for seq in team_sequences:
    states = model.predict(seq)
    hidden_states.append(states)

# Step 11: Map hidden states to actual results using majority vote
flattened_targets = np.concatenate(team_targets)
flattened_states = np.concatenate(hidden_states)

state_to_result = {}
for s in np.unique(flattened_states):
    idx = np.where(flattened_states == s)[0]
    if len(idx) > 0:
        common_result = mode(flattened_targets[idx], keepdims=True)[0][0]
        state_to_result[s] = common_result

# Step 12: Predict based on hidden state mapping
predictions = [state_to_result[s] for s in flattened_states]

# Step 13: Evaluation
print("HMM Accuracy:", accuracy_score(flattened_targets, predictions))
print("Classification Report:\n", classification_report(flattened_targets, predictions))

